"""Convert the startup artwork to the current ST7305 RAM wire format."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
source = Image.open(ROOT / "resources" / "boot_reference.png").convert("L")
width, height = 384, 168
scale = min(width / source.width, height / source.height)
size = (round(source.width * scale), round(source.height * scale))
art = source.resize(size, Image.Resampling.LANCZOS).point(lambda p: 255 if p >= 128 else 0)
canvas = Image.new("L", (width, height), 0)
canvas.paste(art, ((width - size[0]) // 2, (height - size[1]) // 2))
# U8G2_R3 mapping: physical(x,y) = logical(y, 383-x).
# Existing ST7305 driver sends each pair of physical rows as 42 bytes;
# conTable swaps each vertical two-bit pair before packing four columns.
data = bytearray()
for pair in range(width // 2):
    for group in range(height // 4):
        packed = 0
        for column in range(4):
            y = group * 4 + column
            top = canvas.getpixel((width - 1 - pair * 2, y)) == 0
            bottom = canvas.getpixel((width - 2 - pair * 2, y)) == 0
            packed = (packed << 2) | (top << 1) | bottom
        data.append(packed)
lines = [", ".join(f"0x{b:02x}" for b in data[i:i+16]) for i in range(0, len(data), 16)]
header = """/* Generated by tools/generate_boot_assets.py from resources/boot_reference.png.
 * ST7305 168x384 native RAM order for the existing U8G2_R3 orientation.
 * Each two physical rows contain 42 bytes; 1 = black, 0 = white.
 */
#ifndef UI_BOOT_ASSETS_H
#define UI_BOOT_ASSETS_H
#include <stdint.h>
#define UI_BOOT_WIDTH 384u
#define UI_BOOT_HEIGHT 168u
static const uint8_t ui_boot_st7305[8064] = {
""" + "\n".join("    " + line + "," for line in lines) + "\n};\n#endif\n"
(ROOT / "APP" / "include" / "ui_boot_assets.h").write_text(header, encoding="ascii")
output = ROOT / "verification"
output.mkdir(exist_ok=True)
canvas.save(output / "boot_expected.png")
print(f"Generated {len(data)} bytes, artwork {size}, canvas {width}x{height}")
